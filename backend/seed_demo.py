"""Seed an offline demo account (spec 21.5 demo mode): no internet, no language model.

Creates (or reuses) a `demo` account that is already consented, loads the six ready-made topics from the pre-written
question bank, and gives most concepts a short, plausible study history spread over the last few days, so the Today screen
shows concepts that are due now, coming up later and new, and the retention curves have something to draw.

    python -m backend.seed_demo                       # prints the password once
    python -m backend.seed_demo --password demo-pass  # choose it yourself
    python -m backend.seed_demo --reset               # delete the demo account's data first and seed again

The history is generated by the same learning engine the app uses, so it is consistent with what a real student would have.
"""
from __future__ import annotations

import argparse
import json
import time

from backend import auth, config, db, engine, fallback, llm, topics

DEMO_USER = "demo"
DAY_MS = config.MS_PER_DAY
# (days ago the first quiz was, correctness of the review answers given since). An empty list: only the first quiz so far.
HISTORY = [
    (7.0, [True, True]), (6.0, [True]), (5.0, [False, True]), (4.0, []), (3.0, [True]), (2.0, []),
]
LEAVE_NEW = {"korean_hangul": 5, "photography_basics": 5, "central_asia": 5, "cognitive_biases": 5, "how_gps_works": 6, "nutrition_labels": 5}     # concepts from this position on stay new, so the demo also shows first quizzes


def _clear(conn, uid: int) -> None:
    conn.execute("DELETE FROM responses WHERE user_id=?", (uid,))
    conn.execute("DELETE FROM state WHERE user_id=?", (uid,))
    conn.execute("DELETE FROM questions WHERE concept_id IN (SELECT concept_id FROM concepts WHERE user_id=?)", (uid,))
    conn.execute("DELETE FROM concepts WHERE user_id=?", (uid,))
    conn.execute("DELETE FROM notes WHERE user_id=?", (uid,))
    conn.execute("UPDATE users SET ability=?, n_answers=0 WHERE user_id=?", (config.DEFAULT_ABILITY, uid))


def _answer(conn, models, user_id: int, concept_id: int, arm: str, question_id: int, state: dict, ability: float, correct: bool, ts: int, key: str):
    """One answer through the real engine; writes the same columns the API writes. Returns the new state and ability."""
    new_state, ability, info = engine.apply_response(models, state, ability, arm, correct, 9000, ts)
    conn.execute("""INSERT INTO state(user_id,concept_id,mastery,n_sessions,n_responses,last_ts,stability_days,t_review_days,due_at,remem_due_at,sm2_ef,sm2_reps,sm2_interval)
                    VALUES (:u,:c,:mastery,:n_sessions,:n_responses,:last_ts,:stability_days,:t_review_days,:due_at,:remem_due_at,:sm2_ef,:sm2_reps,:sm2_interval)
                    ON CONFLICT(user_id,concept_id) DO UPDATE SET mastery=:mastery,n_sessions=:n_sessions,n_responses=:n_responses,last_ts=:last_ts,
                    stability_days=:stability_days,t_review_days=:t_review_days,due_at=:due_at,remem_due_at=:remem_due_at,sm2_ef=:sm2_ef,sm2_reps=:sm2_reps,sm2_interval=:sm2_interval""",
                 {"u": user_id, "c": concept_id, **new_state})
    conn.execute("""INSERT INTO responses(user_id,concept_id,question_id,idem_key,ts,correct,rt_ms,pred_R,elapsed_days,mode,arm,was_due,stability_after,mastery_after,result_json)
                    VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                 (user_id, concept_id, question_id, key, ts, int(correct), 9000, info["pred_R"], info["elapsed_days"], info["mode"], arm,
                  None if info["was_due"] is None else int(info["was_due"]), new_state["stability_days"], new_state["mastery"], json.dumps({"correct": correct, "demo": True})))
    return new_state, ability


def seed(conn, password: str | None = None, reset: bool = False, now_ms: int | None = None) -> dict:
    """Create the demo account and its data in `conn`. Returns {"username", "password" (None if it already existed), "concepts"}."""
    now = now_ms if now_ms is not None else int(time.time() * 1000)
    row = conn.execute("SELECT user_id FROM users WHERE username=?", (DEMO_USER,)).fetchone()
    shown_pw = None
    if row is None:
        from backend.admin_create_user import gen_password
        shown_pw = password or gen_password()
        uid = auth.create_user(conn, DEMO_USER, shown_pw, "demo")
    else:
        uid = row["user_id"]
        if password:
            h, salt = auth.hash_password(password)
            conn.execute("UPDATE users SET pw_hash=?, salt=? WHERE user_id=?", (h, salt, uid))
            shown_pw = password
    if reset:
        _clear(conn, uid)
    if conn.execute("SELECT COUNT(*) FROM concepts WHERE user_id=?", (uid,)).fetchone()[0]:
        return {"username": DEMO_USER, "password": shown_pw, "concepts": 0, "note": "demo data already present (use --reset to rebuild)"}
    conn.execute("UPDATE users SET consent_at=?, consent_version=? WHERE user_id=?", (now, config.CONSENT_VERSION, uid))
    conn.execute("INSERT OR IGNORE INTO profiles(user_id,full_name,contact,age,known_topics,created_at) VALUES (?,?,?,?,?,?)",
                 (uid, "Demo", "demo@example.com", 21, "[]", now))              # the offline demo skips the sign-up form
    models = engine.Models.load()
    ability = config.DEFAULT_ABILITY
    n_concepts, k = 0, 0
    for t in topics.all_topics():
        concepts = fallback.concepts_for(t["id"])
        if not concepts:
            raise RuntimeError(f"no valid fallback bank for topic {t['id']}")
        nid = conn.execute("INSERT INTO notes(user_id,title,text,status,created_at,topic_id) VALUES (?,?,?,?,?,?)",
                           (uid, t["title"], t["text"], "done", now - 8 * DAY_MS, t["id"])).lastrowid
        for pos, c in enumerate(concepts):
            cid = conn.execute("INSERT INTO concepts(user_id,note_id,name,source_span,arm,created_at) VALUES (?,?,?,?,?,?)",
                               (uid, nid, c.name, c.source_span, "remem", now - 8 * DAY_MS)).lastrowid
            qids = [conn.execute("INSERT INTO questions(concept_id,variant_no,stem,options_json,correct_idx,is_final_test,created_at) VALUES (?,?,?,?,?,?,?)",
                                 (cid, i, q.stem, json.dumps(q.options), q.correct_index, 1 if i == llm.N_VARIANTS else 0, now - 8 * DAY_MS)).lastrowid
                    for i, q in enumerate(c.questions, start=1)]
            n_concepts += 1
            if pos >= LEAVE_NEW.get(t["id"], 10 ** 9):
                continue
            days_ago, later = HISTORY[(pos + k) % len(HISTORY)]
            state: dict = {}
            ts = now - int(days_ago * DAY_MS)
            gap = int(days_ago * DAY_MS / (len(later) + 1))                # later answers are spread evenly, the last one about a gap before now
            for j, ok in enumerate([True] + list(later)):
                state, ability = _answer(conn, models, uid, cid, "remem", qids[j % 4], state, ability, ok, ts, f"demo-{cid}-{j}")
                ts += gap
            k += 1
    conn.execute("UPDATE users SET ability=?, n_answers=(SELECT COUNT(*) FROM responses WHERE user_id=?) WHERE user_id=?", (ability, uid, uid))
    return {"username": DEMO_USER, "password": shown_pw, "concepts": n_concepts}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--password", help="password for the demo account (default: generated and printed once)")
    ap.add_argument("--reset", action="store_true", help="delete the demo account's data and seed again")
    a = ap.parse_args()
    db.init_db()
    with db.session() as conn:
        r = seed(conn, a.password, a.reset)
    print(f"Demo account '{r['username']}': {r['concepts']} concepts loaded." + (f" Password (shown once): {r['password']}" if r["password"] else ""))
    if r.get("note"):
        print(r["note"])


if __name__ == "__main__":
    main()
